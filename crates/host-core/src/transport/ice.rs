//! ICE candidate gathering and nomination.
//!
//! ICE candidate gathering, nomination, and relay signaling.

use std::sync::Arc;
use std::time::Duration;
use std::{future::Future, pin::Pin};

use futures_util::{SinkExt, StreamExt};
use tokio::sync::mpsc;
use tokio::sync::Mutex;
use tokio_tungstenite::{tungstenite::Message, WebSocketStream};
use webrtc_ice::agent::{agent_config::AgentConfig, Agent};
use webrtc_ice::candidate::candidate_base::unmarshal_candidate;
use webrtc_ice::candidate::Candidate;
use webrtc_util::conn::Conn;

/// Information exchanged through the relay while establishing ICE.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IceSignal {
    /// A candidate's `Candidate::marshal()` wire representation.
    Candidate(String),
    /// The ICE credentials generated by the sending agent.
    Credentials { ufrag: String, pwd: String },
}

/// The signaling seam used by ICE. Implementations may map these signals to
/// relay control frames, an in-process channel, or another signaling system.
#[async_trait::async_trait]
pub trait IceSignaling: Send {
    async fn send_local(&mut self, signal: IceSignal);
    async fn recv_remote(&mut self) -> Option<IceSignal>;
}

/// ICE signaling over the paired relay WebSocket.
///
/// Credentials use the wire convention `cred:<ufrag>:<pwd>` in the existing
/// `Control::Ice.cand` field. ICE signaling is only read between SPAKE2 key
/// confirmation and media transport selection; after timeout, the shared
/// WebSocket is used by `RelayTransport` again.
pub struct RelayIceSignaling<S> {
    ws: Arc<Mutex<WebSocketStream<S>>>,
    session: String,
}

impl<S> RelayIceSignaling<S> {
    pub(crate) fn new(
        relay: &crate::transport::RelayTransport<S>,
        session: impl Into<String>,
    ) -> Self {
        Self {
            ws: relay.shared_socket(),
            session: session.into(),
        }
    }
}

fn encode_signal(signal: &IceSignal) -> String {
    match signal {
        IceSignal::Candidate(candidate) => candidate.clone(),
        IceSignal::Credentials { ufrag, pwd } => format!("cred:{ufrag}:{pwd}"),
    }
}

fn decode_signal(cand: &str) -> Option<IceSignal> {
    let credentials = cand.strip_prefix("cred:")?;
    let (ufrag, pwd) = credentials.split_once(':')?;
    if ufrag.is_empty() || pwd.is_empty() {
        return None;
    }
    Some(IceSignal::Credentials {
        ufrag: ufrag.to_owned(),
        pwd: pwd.to_owned(),
    })
}

fn decode_control(session: &str, body: &[u8]) -> Option<IceSignal> {
    match protocol::control::Control::from_bytes(body)? {
        protocol::control::Control::Ice {
            session: remote_session,
            cand,
        } if remote_session == session => decode_signal(&cand).or(Some(IceSignal::Candidate(cand))),
        _ => None,
    }
}

#[async_trait::async_trait]
impl<S> IceSignaling for RelayIceSignaling<S>
where
    S: tokio::io::AsyncRead + tokio::io::AsyncWrite + Unpin + Send,
{
    async fn send_local(&mut self, signal: IceSignal) {
        let control = protocol::control::Control::Ice {
            session: self.session.clone(),
            cand: encode_signal(&signal),
        };
        let mut ws = self.ws.lock().await;
        let _ = ws
            .send(Message::Binary(protocol::frame::wrap(
                protocol::Tag::Control,
                &control.to_bytes(),
            )))
            .await;
    }

    async fn recv_remote(&mut self) -> Option<IceSignal> {
        let mut ws = self.ws.lock().await;
        while let Some(message) = ws.next().await {
            if let Ok(Message::Binary(bytes)) = message {
                if let Some((protocol::Tag::Control, body)) = protocol::frame::unwrap(&bytes) {
                    if let Some(signal) = decode_control(&self.session, body) {
                        return Some(signal);
                    }
                }
            }
        }
        None
    }
}

/// Result of the ICE nomination attempt.
pub enum IceOutcome {
    Nominated(Arc<dyn Conn + Send + Sync>),
    TimedOut,
}

type DialFuture =
    Pin<Box<dyn Future<Output = Result<Arc<dyn Conn + Send + Sync>, webrtc_ice::Error>> + Send>>;

/// Encode a candidate for signaling.
pub fn encode_candidate(candidate: &dyn Candidate) -> String {
    candidate.marshal()
}

/// Decode a candidate received through signaling.
pub fn decode_candidate(wire: &str) -> Result<Arc<dyn Candidate + Send + Sync>, webrtc_ice::Error> {
    Ok(Arc::new(unmarshal_candidate(wire)?))
}

/// Gather local candidates, exchange ICE data through `signaling`, and
/// nominate a usable connection before `deadline` elapses.
pub async fn establish_ice<S: IceSignaling>(
    agent_config: AgentConfig,
    controlling: bool,
    mut signaling: S,
    deadline: Duration,
) -> IceOutcome {
    let agent = match Agent::new(agent_config).await {
        Ok(agent) => Arc::new(agent),
        Err(_) => return IceOutcome::TimedOut,
    };

    let (local_tx, mut local_rx) = mpsc::channel::<IceSignal>(32);
    agent.on_candidate(Box::new(move |candidate| {
        let local_tx = local_tx.clone();
        Box::pin(async move {
            if let Some(candidate) = candidate {
                let _ = local_tx
                    .send(IceSignal::Candidate(encode_candidate(candidate.as_ref())))
                    .await;
            }
        })
    }));

    if agent.gather_candidates().is_err() {
        return IceOutcome::TimedOut;
    }

    let (ufrag, pwd) = agent.get_local_user_credentials().await;
    signaling
        .send_local(IceSignal::Credentials { ufrag, pwd })
        .await;

    let deadline_sleep = tokio::time::sleep(deadline);
    tokio::pin!(deadline_sleep);
    let mut dial: Option<DialFuture> = None;
    let (cancel_tx, cancel_rx) = mpsc::channel(1);
    let mut cancel_rx = Some(cancel_rx);

    loop {
        tokio::select! {
            _ = &mut deadline_sleep => {
                let _ = cancel_tx.send(()).await;
                let _ = agent.close().await;
                return IceOutcome::TimedOut;
            }
            local = local_rx.recv() => {
                if let Some(signal) = local {
                    signaling.send_local(signal).await;
                }
            }
            remote = signaling.recv_remote() => {
                match remote {
                    Some(IceSignal::Candidate(wire)) => {
                        if let Ok(candidate) = decode_candidate(&wire) {
                            let _ = agent.add_remote_candidate(&candidate);
                        }
                    }
                    Some(IceSignal::Credentials { ufrag, pwd }) => {
                        // Start the dial/accept exactly once. Duplicate
                        // Credentials signals (a relay reconnect/retry can
                        // resend them) are ignored — guarding on dial.is_none()
                        // means cancel_rx is only ever consumed once.
                        if dial.is_none() {
                            if let Some(cancel_rx) = cancel_rx.take() {
                                let agent = Arc::clone(&agent);
                                dial = Some(Box::pin(async move {
                                    if controlling {
                                        agent
                                            .dial(cancel_rx, ufrag, pwd)
                                            .await
                                            .map(|conn| conn as Arc<dyn Conn + Send + Sync>)
                                    } else {
                                        agent
                                            .accept(cancel_rx, ufrag, pwd)
                                            .await
                                            .map(|conn| conn as Arc<dyn Conn + Send + Sync>)
                                    }
                                }));
                            }
                        }
                    }
                    None => {
                        let _ = cancel_tx.send(()).await;
                        let _ = agent.close().await;
                        return IceOutcome::TimedOut;
                    }
                }
            }
            result = async {
                match dial.as_mut() {
                    Some(future) => Some(future.await),
                    None => None,
                }
            }, if dial.is_some() => {
                if let Some(Ok(conn)) = result {
                    return IceOutcome::Nominated(conn);
                }
                let _ = agent.close().await;
                return IceOutcome::TimedOut;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use webrtc_ice::candidate::candidate_base::unmarshal_candidate;

    #[test]
    fn relay_signal_round_trips_candidate_and_credentials() {
        let signals = [
            IceSignal::Candidate("candidate:1 1 udp 1 192.0.2.1 5000 typ host".into()),
            IceSignal::Credentials {
                ufrag: "ufrag".into(),
                pwd: "password".into(),
            },
        ];
        for signal in signals {
            let wire = encode_signal(&signal);
            let decoded =
                decode_signal(&wire).unwrap_or_else(|| IceSignal::Candidate(wire.clone()));
            assert_eq!(decoded, signal);
        }
    }

    #[test]
    fn candidate_wire_round_trips() {
        let wire = "123456789 1 udp 2130706431 192.168.1.20 49152 typ host";
        let candidate = unmarshal_candidate(wire).expect("known candidate parses");
        assert_eq!(encode_candidate(&candidate), wire);
        assert_eq!(
            encode_candidate(decode_candidate(wire).unwrap().as_ref()),
            wire
        );
    }

    struct NoRemote;

    #[async_trait::async_trait]
    impl IceSignaling for NoRemote {
        async fn send_local(&mut self, _signal: IceSignal) {}

        async fn recv_remote(&mut self) -> Option<IceSignal> {
            std::future::pending().await
        }
    }

    #[tokio::test]
    async fn establish_times_out_without_remote_signals() {
        let outcome = establish_ice(
            AgentConfig::default(),
            true,
            NoRemote,
            Duration::from_millis(20),
        )
        .await;
        assert!(matches!(outcome, IceOutcome::TimedOut));
    }
}
